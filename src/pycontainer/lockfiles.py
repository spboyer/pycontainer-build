def _requirement_key(
    name: str, extras: Sequence[str], specifier: str, marker: Optional[str], environment, scenarios, source: str
) -> Tuple:
    try:
        specifiers = SpecifierSet(specifier or "")
    except InvalidSpecifier as exc:
        raise LockfileError(f"Invalid version specifier in {source}: {specifier!r}") from exc
    applies = () if environment is None else tuple(
        _marker_applies(marker, environment, source, extra) for extra in scenarios
    )
    return (canonical_name(name), tuple(sorted(canonical_name(extra) for extra in extras)), specifiers, applies)


def _pep508_key(text: str, environment, scenarios, source: str, extra: Optional[str] = None) -> Tuple:
    try:
        requirement = Requirement(text)
    except InvalidRequirement as exc:
        raise LockfileError(f"Invalid requirement in {source}: {text!r}") from exc
    if requirement.url:
        raise LockfileError(f"Direct URL requirement {requirement.name} in {source} is unsupported.")
    marker = str(requirement.marker) if requirement.marker else None
    if extra is not None:
        clause = f"extra == '{extra}'"
        marker = f"({marker}) and {clause}" if marker else clause
    return _requirement_key(
        requirement.name, sorted(requirement.extras), str(requirement.specifier), marker, environment, scenarios, source
    )


def _lock_requirement_key(entry: dict, environment, scenarios, source: str) -> Tuple:
    if not {"url", "git", "path", "directory", "editable"}.isdisjoint(entry):
        raise LockfileError(f"uv.lock requirement {entry.get('name')} uses an unsupported source.")
    return _requirement_key(
        entry.get("name", ""), entry.get("extras", []), entry.get("specifier", ""),
        entry.get("marker"), environment, scenarios, source,
    )


def _check_uv_fresh(lock: dict, root: dict, pyproject: dict, environment) -> None:
    project = pyproject.get("project", {})
    if project.get("requires-python"):
        try:
            matches = (
                bool(lock.get("requires-python"))
                and SpecifierSet(lock["requires-python"]) == SpecifierSet(project["requires-python"])
            )
        except InvalidSpecifier as exc:
            raise LockfileError("Invalid requires-python in pyproject.toml or uv.lock.") from exc
        if not matches:
            raise _stale("uv.lock", "uv lock")
    optional = project.get("optional-dependencies", {})
    scenarios = ("", *sorted(canonical_name(extra) for extra in optional))
    expected = sorted(
        [_pep508_key(item, environment, scenarios, "pyproject.toml") for item in project.get("dependencies", [])]
        + [
            _pep508_key(item, environment, scenarios, "pyproject.toml", canonical_name(extra))
            for extra, items in optional.items()
            for item in items
        ],
        key=repr,
    )
    metadata = root.get("metadata", {})
    actual = sorted(
        (_lock_requirement_key(item, environment, scenarios, "uv.lock") for item in metadata.get("requires-dist", [])),
        key=repr,
    )
    expected_groups = {}
    groups = dict(pyproject.get("dependency-groups", {}))
    legacy = pyproject.get("tool", {}).get("uv", {}).get("dev-dependencies")
    if legacy:
        groups.setdefault("dev", []).extend(legacy)
    for group, items in groups.items():
        if any(not isinstance(item, str) for item in items):
            raise LockfileError("uv dependency-group includes are unsupported for lockfile staging.")
        expected_groups[canonical_name(group)] = sorted(
            (_pep508_key(item, environment, ("",), "pyproject.toml") for item in items), key=repr
        )
    actual_groups = {
        canonical_name(group): sorted(
            (_lock_requirement_key(item, environment, ("",), "uv.lock") for item in items), key=repr
        )
        for group, items in metadata.get("requires-dev", {}).items()
    }
    if expected != actual or expected_groups != actual_groups:
        raise _stale("uv.lock", "uv lock")


def _check_uv_complete(pyproject: dict, environment, selected, visited) -> None:
    """Fail when the locked root graph omits a manifest dependency for the target."""
    versions: Dict[str, List[str]] = {}
    for name, version in selected:
        versions.setdefault(name, []).append(version)
    for text in pyproject.get("project", {}).get("dependencies", []):
        try:
            requirement = Requirement(text)
        except InvalidRequirement as exc:
            raise LockfileError(f"Invalid requirement in pyproject.toml: {text!r}") from exc
        marker = str(requirement.marker) if requirement.marker else None
        if not _marker_applies(marker, environment, "pyproject.toml"):
            continue
        name = canonical_name(requirement.name)
        matches = [v for v in versions.get(name, []) if requirement.specifier.contains(v, prereleases=True)]
        extras = {canonical_name(extra) for extra in requirement.extras}
        covered = {
            canonical_name(extra)
            for state_name, state_version, state_extras in visited
            if state_name == name and state_version in matches
            for extra in state_extras
        }
        nonempty_extras = {
            canonical_name(extra)
            for (entry_name, entry_version), entry in selected.items()
            if entry_name == name and entry_version in matches
            for extra, dependencies in entry.get("optional-dependencies", {}).items()
            if dependencies
        }
        if not matches or not (extras & nonempty_extras) <= covered:
            raise LockfileError(
                f"uv.lock does not lock {requirement} for the target environment; run `uv lock`."
            )


def _uv_environment_markers(values, source: str) -> set[str]:
    if values is None:
        return set()
    if not isinstance(values, list) or any(not isinstance(value, str) or not value.strip() for value in values):
        raise LockfileError(f"Invalid supported environments in {source}.")
    markers = set()
    for value in values:
        try:
            marker = str(Marker(value))
        except InvalidMarker as exc:
            raise LockfileError(f"Invalid environment marker in {source}: {value!r}") from exc
        tokens = _marker_tokens(marker, source)
        # These bounds are equivalent for final CPython releases; do not rewrite quoted values.
        for index in range(len(tokens) - 3, -1, -1):
            variable, operator, version = tokens[index:index + 3]
            if (
                variable.type == tokenize.NAME
                and variable.string == "python_version"
                and operator.type == tokenize.OP
                and operator.string in {">=", "<"}
                and version.type == tokenize.STRING
                and re.fullmatch(r"""(['"])\d+\.\d+\1""", version.string)
            ):
                if variable.start[0] != 1:
                    raise LockfileError(f"Cannot normalize environment marker in {source}: {value!r}")
                start, end = variable.start[1], variable.end[1]
                marker = marker[:start] + "python_full_version" + marker[end:]
        markers.add(marker)
    return markers


def _check_uv_environments(lock: dict, settings: dict, environment) -> None:
    configured = _uv_environment_markers(settings.get("environments"), "tool.uv.environments")
    locked = _uv_environment_markers(lock.get("supported-markers"), "uv.lock")
    if configured != locked:
        raise LockfileError(
            "Cannot verify uv.lock supported environments match tool.uv.environments; "
            "run `uv lock` or use unrestricted environments."
        )
    if environment is not None and locked:
        applies = [
            _marker_applies(marker, environment, "uv.lock supported environments") for marker in sorted(locked)
        ]
        if not any(applies):
            raise LockfileError("uv.lock does not support the target environment; update the environments and relock.")


def _check_uv_indexes(path: Path, lock: dict, settings: dict) -> None:
    if (path.parent / "uv.toml").exists() or {"index-url", "extra-index-url", "find-links"} & settings.keys():
        raise LockfileError("uv.lock staging requires project indexes to use [[tool.uv.index]] in pyproject.toml.")
    indexes = settings.get("index", [])
    allowed = {
        _index_url(index.get("url", ""), "tool.uv.index")
        for index in indexes
    }
    if not any(index.get("default") for index in indexes):
        allowed.add(None)  # uv's implicit PyPI index
    for entry in lock.get("package", []):
        registry = entry.get("source", {}).get("registry")
        if registry and _index_url(registry, "uv.lock package registry") not in allowed:
            raise _stale("uv.lock", "uv lock")


def _load_uv(path: Path, environment, context_dir: Path):
    lock = _read_toml(path)
    pyproject = _read_toml(_manifest(path, "pyproject.toml", context_dir))
    _project_requirements(pyproject, "pyproject.toml")
    if lock.get("version") != 1:
        raise LockfileError("uv.lock version is unsupported; relock with a current uv.")
    if "manifest" in lock:
        raise LockfileError("uv workspaces, constraints and overrides are unsupported for lockfile staging.")
    uv_settings = pyproject.get("tool", {}).get("uv", {})
    unsupported = sorted(
        {"sources", "workspace", "override-dependencies", "constraint-dependencies"} & set(uv_settings)
    )
    if unsupported:
        raise LockfileError(f"uv tool.uv.{unsupported[0]} is unsupported for lockfile staging.")
    _check_uv_environments(lock, uv_settings, environment)
    _check_uv_indexes(path, lock, uv_settings)

    by_name: Dict[str, List[dict]] = {}
    roots = []
    for entry in lock.get("package", []):
        source = entry.get("source", {})
        if source.get("virtual") == "." or source.get("editable") == ".":
            roots.append(entry)
        by_name.setdefault(canonical_name(entry.get("name", "")), []).append(entry)
    if len(roots) != 1:
        raise LockfileError("uv.lock must contain exactly one root project package.")
    root = roots[0]
    project_name = pyproject.get("project", {}).get("name")
    if not project_name or canonical_name(project_name) != canonical_name(root.get("name", "")):
        raise _stale("uv.lock", "uv lock")
    _check_uv_fresh(lock, root, pyproject, environment)
    if environment is None:
        return [], []
    _require_python(lock.get("requires-python"), environment, "uv.lock")

    selected: Dict[Tuple[str, str], dict] = {}
    pending = [(dependency, root.get("name")) for dependency in root.get("dependencies", [])]
    visited = set()
    while pending:
        dependency, parent = pending.pop()
        name = canonical_name(dependency.get("name", ""))
        if not _marker_applies(dependency.get("marker"), environment, f"uv.lock dependency of {parent}"):
            continue
        candidates = [
            entry
            for entry in by_name.get(name, [])
            if dependency.get("version") in (None, entry.get("version"))
            and dependency.get("source") in (None, entry.get("source"))
        ]
        candidates = [
            entry
            for entry in candidates
            if any(
                _marker_applies(marker, environment, f"uv.lock package {name}")
                for marker in entry.get("resolution-markers", [None])
            )
        ]
        if len(candidates) != 1:
            raise LockfileError(f"uv.lock dependency {name} of {parent} does not identify one locked package.")
        entry = candidates[0]
        extras = tuple(sorted(dependency.get("extra", [])))
        state = (name, entry.get("version"), extras)
        if state in visited:
            continue
        visited.add(state)
        selected[(name, entry.get("version"))] = entry
        pending.extend((child, name) for child in entry.get("dependencies", []))
        optional = entry.get("optional-dependencies", {})
        for extra in extras:
            pending.extend((child, name) for child in optional.get(extra, ()))
    _check_uv_complete(pyproject, environment, selected, visited)

    packages, indexes = [], []
    for (name, _), entry in sorted(selected.items()):
        registry = entry.get("source", {}).get("registry")
        if not registry:
            kind = next(iter(entry.get("source", {})), "unknown")
            raise LockfileError(
                f"uv.lock package {name} uses an unsupported {kind} source; only "
                "registry packages are supported."
            )
        indexes.append(_index_url(registry, f"uv.lock package {name}"))
        artifacts = list(entry.get("wheels", []))
        if not artifacts:
            raise LockfileError(
                f"uv.lock package {name} {entry.get('version')} has no locked wheels; "
                "source distributions are not supported."
            )
        packages.append(_package(name, entry.get("version"), [item.get("hash") for item in artifacts], "uv.lock"))
    return packages, _ordered_unique(indexes)
