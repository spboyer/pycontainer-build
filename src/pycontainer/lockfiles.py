"""Read Poetry, Pipenv, PDM and uv lockfiles into hash-pinned requirements.

The selected lock is validated against its project manifest, evaluated for the
target image environment, and rendered as ``name==version --hash=...`` lines
that the target-aware, wheel-only pip staging installs with ``--no-deps``.
"""
import hashlib
import json
import re
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple
from urllib.parse import urlsplit

try:
    from packaging.markers import InvalidMarker, Marker
    from packaging.requirements import InvalidRequirement, Requirement
    from packaging.specifiers import InvalidSpecifier, SpecifierSet
except ImportError:  # pragma: no cover - exercised when only pip is installed
    try:
        from pip._vendor.packaging.markers import InvalidMarker, Marker
        from pip._vendor.packaging.requirements import InvalidRequirement, Requirement
        from pip._vendor.packaging.specifiers import InvalidSpecifier, SpecifierSet
    except ImportError:
        Marker = Requirement = SpecifierSet = None
        InvalidMarker = InvalidRequirement = InvalidSpecifier = ValueError


LOCKFILE_KINDS = {
    "poetry.lock": "poetry",
    "Pipfile.lock": "pipenv",
    "pdm.lock": "pdm",
    "uv.lock": "uv",
}
MAX_LOCKFILE_BYTES = 16 * 1024 * 1024
_PYPI_INDEXES = {"https://pypi.org/simple", "https://pypi.python.org/simple"}
_PIPFILE_SECTIONS = {"source", "packages", "dev-packages", "requires", "scripts", "pipfile", "pipenv"}
_DEFAULT_PIPFILE_SOURCE = {"name": "pypi", "url": "https://pypi.org/simple", "verify_ssl": True}
_HASH_LENGTHS = {"sha256": 64, "sha384": 96, "sha512": 128}
_UNKNOWN_MARKER_VARIABLES = ("platform_release", "platform_version")
_PLACEHOLDER = re.compile(r"\$\{[A-Za-z_][A-Za-z0-9_]*\}")
_MACHINES = {"amd64": "x86_64", "arm64": "aarch64"}


class LockfileError(ValueError):
    """The selected lockfile cannot be used for a reproducible target install."""


@dataclass(frozen=True)
class LockedPackage:
    name: str
    version: str
    hashes: Tuple[str, ...]


@dataclass(frozen=True)
class LockSelection:
    kind: str
    path: Path
    packages: Tuple[LockedPackage, ...]
    index_urls: Tuple[str, ...] = ()

    def render_requirements(self) -> str:
        lines = [f"# Generated by pycontainer from {self.path.name}; do not edit."]
        lines.extend(f"--extra-index-url {url}" for url in self.index_urls)
        for package in self.packages:
            hashes = " ".join(f"--hash={value}" for value in package.hashes)
            lines.append(f"{package.name}=={package.version} {hashes}")
        return "\n".join(lines) + "\n"


def canonical_name(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def detect_lockfile(context_dir: Path) -> Optional[str]:
    """Return the single supported lockfile at the context root, if any."""
    found = sorted(name for name in LOCKFILE_KINDS if (Path(context_dir) / name).is_file())
    if len(found) > 1:
        raise LockfileError(
            f"Multiple lockfiles found ({', '.join(found)}); select one with "
            "--lockfile or [build].lockfile, or disable them with --no-lockfile."
        )
    return found[0] if found else None


def target_environment(
    os_name: str, arch: str, python_version: str, python_full_version: Optional[str]
) -> Dict[str, Optional[str]]:
    """Marker values for the target image; unknown values stay ``None``."""
    if os_name != "linux" or arch not in _MACHINES:
        raise LockfileError(f"Lockfile staging does not support target {os_name}/{arch}.")
    return {
        "implementation_name": "cpython",
        "implementation_version": python_full_version,
        "os_name": "posix",
        "platform_machine": _MACHINES[arch],
        "platform_python_implementation": "CPython",
        "platform_release": None,
        "platform_system": "Linux",
        "platform_version": None,
        "python_full_version": python_full_version,
        "python_version": python_version,
        "sys_platform": "linux",
    }


def load_lockfile(
    context_dir: Path, relative: Path, environment: Dict[str, Optional[str]]
) -> LockSelection:
    """Validate a lock against its manifest and select the target's packages."""
    path, kind, reader = _lock_reader(context_dir, relative)
    if environment.get("python_full_version") is None:
        raise LockfileError(
            "Lockfile staging needs the full target Python version; use a base image "
            "with PYTHON_VERSION=<major>.<minor>.<patch> metadata."
        )
    packages, indexes = reader(path, environment)
    return LockSelection(kind, Path(relative), _finalize(packages, path.name), tuple(indexes))


def preflight_lockfile(context_dir: Path, relative: Path) -> None:
    """Check locally verifiable freshness before a dry run, without a target image."""
    path, _, reader = _lock_reader(context_dir, relative)
    reader(path, None)


def _lock_reader(context_dir: Path, relative: Path):
    path = Path(context_dir) / relative
    kind = LOCKFILE_KINDS.get(path.name)
    if kind is None:
        raise LockfileError(
            f"Unsupported lockfile name {path.name!r}; expected one of: "
            f"{', '.join(sorted(LOCKFILE_KINDS))}."
        )
    if not path.is_file():
        raise LockfileError(f"Lockfile not found: {relative.as_posix()}")
    if not path.resolve().is_relative_to(Path(context_dir).resolve()):
        raise LockfileError(f"Lockfile must be inside the build context: {relative.as_posix()}")
    if path.stat().st_size > MAX_LOCKFILE_BYTES:
        raise LockfileError(f"Lockfile exceeds the {MAX_LOCKFILE_BYTES}-byte limit: {path.name}")
    if Marker is None:
        raise LockfileError("Lockfile staging requires pip in the Python interpreter running pycontainer.")
    reader = {"poetry": _load_poetry, "pipenv": _load_pipenv, "pdm": _load_pdm, "uv": _load_uv}[kind]
    return path, kind, reader


def _finalize(packages: Iterable[LockedPackage], source: str) -> Tuple[LockedPackage, ...]:
    selected: Dict[str, LockedPackage] = {}
    for package in packages:
        existing = selected.get(package.name)
        if existing and existing.version != package.version:
            raise LockfileError(
                f"{source} selects both {package.name} {existing.version} and "
                f"{package.version} for the target environment."
            )
        if existing:
            package = LockedPackage(
                package.name, package.version, tuple(sorted(set(existing.hashes) | set(package.hashes)))
            )
        selected[package.name] = package
    return tuple(selected[name] for name in sorted(selected))


def _read_toml(path: Path) -> dict:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        raise LockfileError(f"Unable to parse {path.name}: {exc}") from exc


def _manifest(lock_path: Path, name: str) -> Path:
    manifest = lock_path.parent / name
    if not manifest.is_file():
        raise LockfileError(f"{lock_path.name} requires {name} next to it to verify the lock is current.")
    return manifest


def _stale(lock_name: str, command: str) -> LockfileError:
    return LockfileError(
        f"{lock_name} is out of date with its project manifest; run `{command}` and rebuild."
    )


def _marker_applies(
    marker: Optional[str], environment: Dict[str, Optional[str]], source: str, extra: str = ""
) -> bool:
    if marker is None or not str(marker).strip():
        return True
    try:
        parsed = Marker(str(marker))
    except InvalidMarker as exc:
        raise LockfileError(f"Invalid environment marker in {source}: {marker!r}") from exc
    for variable, value in environment.items():
        if value is None and re.search(rf"\b{variable}\b", str(parsed)):
            raise LockfileError(
                f"Cannot evaluate marker {str(parsed)!r} in {source} for the target "
                f"image because {variable} is unknown."
            )
    values = {key: value or "" for key, value in environment.items()}
    values["extra"] = extra
    return parsed.evaluate(values)


def _require_python(specifier: Optional[str], environment: Dict[str, Optional[str]], source: str) -> None:
    if not specifier:
        return
    try:
        allowed = SpecifierSet(specifier)
    except InvalidSpecifier as exc:
        raise LockfileError(f"Invalid requires-python {specifier!r} in {source}.") from exc
    version = environment["python_full_version"]
    if not allowed.contains(version, prereleases=True):
        raise LockfileError(
            f"{source} requires Python {specifier}, but the target image provides {version}."
        )


def _hashes(values: Iterable[str], source: str) -> Tuple[str, ...]:
    result = set()
    for value in values:
        algorithm, separator, digest = str(value).partition(":")
        algorithm = algorithm.lower()
        digest = digest.lower()
        if (
            not separator
            or _HASH_LENGTHS.get(algorithm) != len(digest)
            or not re.fullmatch(r"[0-9a-f]+", digest)
        ):
            raise LockfileError(f"Unsupported artifact hash {value!r} for {source}.")
        result.add(f"{algorithm}:{digest}")
    if not result:
        raise LockfileError(f"{source} has no artifact hashes; relock with hashes enabled.")
    return tuple(sorted(result))


def _index_url(url: str, source: str) -> Optional[str]:
    url = str(url)
    if any(ord(char) < 0x21 or ord(char) == 0x7F for char in url):
        raise LockfileError(f"Package index URL for {source} contains whitespace or control characters.")
    parts = urlsplit(url)
    if parts.scheme not in {"http", "https"} or not parts.hostname or parts.fragment:
        raise LockfileError(f"Unsupported package index URL for {source}.")
    userinfo = parts.netloc.rsplit("@", 1)[0].split(":", 1) if "@" in parts.netloc else []
    query_values = [pair.split("=", 1)[-1] for pair in parts.query.split("&") if pair]
    if any(_PLACEHOLDER.sub("", part) for part in [*userinfo, *query_values]):
        raise LockfileError(
            f"Package index URL for {source} contains literal credentials or query values; use "
            "${VARIABLE} placeholders or pip configuration instead."
        )
    normalized = url.rstrip("/")
    return None if normalized.lower() in _PYPI_INDEXES else normalized


def _package(name: str, version, hashes, source: str) -> LockedPackage:
    if not isinstance(version, str) or not re.fullmatch(r"[A-Za-z0-9.!+_-]+", version):
        raise LockfileError(f"{source} has no exact registry version for {name}.")
    return LockedPackage(canonical_name(name), version, _hashes(hashes, f"{name} {version}"))


def _ordered_unique(values: Iterable[Optional[str]]) -> List[str]:
    return list(dict.fromkeys(value for value in values if value))


# --- Poetry ---------------------------------------------------------------

_POETRY_PROJECT_KEYS = ("requires-python", "dependencies", "optional-dependencies")
_POETRY_KEYS = ("dependencies", "source", "extras", "dev-dependencies", "group")
_POETRY_LEGACY_KEYS = ("dependencies", "source", "extras", "dev-dependencies")


def poetry_content_hash(pyproject: dict, *, with_dependency_groups: bool = True) -> str:
    """Poetry 2.x ``Locker._get_content_hash`` over the relevant pyproject data."""
    project = pyproject.get("project", {})
    groups = pyproject.get("dependency-groups", {}) if with_dependency_groups else {}
    poetry = pyproject.get("tool", {}).get("poetry", {})
    relevant_project = {key: project[key] for key in _POETRY_PROJECT_KEYS if project.get(key) is not None}
    relevant_poetry = {}
    for key in _POETRY_KEYS:
        value = poetry.get(key)
        if value is None and (key not in _POETRY_LEGACY_KEYS or relevant_project or groups):
            continue
        relevant_poetry[key] = value
    relevant = {}
    if relevant_project:
        relevant["project"] = relevant_project
    if groups:
        relevant["dependency-groups"] = groups
    if relevant:
        relevant["tool"] = {"poetry": relevant_poetry}
    else:
        relevant = relevant_poetry
    return hashlib.sha256(json.dumps(relevant, sort_keys=True).encode()).hexdigest()


def _load_poetry(path: Path, environment):
    lock = _read_toml(path)
    pyproject = _read_toml(_manifest(path, "pyproject.toml"))
    metadata = lock.get("metadata", {})
    version = str(metadata.get("lock-version", ""))
    match = re.fullmatch(r"(\d+)\.(\d+)", version)
    if not match or int(match.group(1)) != 2 or int(match.group(2)) < 1:
        raise LockfileError(
            f"poetry.lock lock-version {version or '<missing>'} is unsupported; "
            "relock with Poetry 2.0 or newer (lock-version 2.1)."
        )
    expected = metadata.get("content-hash")
    fresh = expected == poetry_content_hash(pyproject)
    if not fresh:
        header = path.read_text(encoding="utf-8").split("\n", 1)[0]
        generated = re.search(r"Poetry (\d+)\.(\d+)", header)
        if generated and (int(generated.group(1)), int(generated.group(2))) < (2, 3):
            fresh = expected == poetry_content_hash(pyproject, with_dependency_groups=False)
    if not fresh:
        raise _stale("poetry.lock", "poetry lock")
    if environment is None:
        return [], []
    _require_python(pyproject.get("project", {}).get("requires-python"), environment, "pyproject.toml")

    packages, indexes = [], []
    for entry in lock.get("package", []):
        name = entry.get("name", "<unnamed>")
        if "main" not in entry.get("groups", []):
            continue
        markers = entry.get("markers")
        marker = markers.get("main") if isinstance(markers, dict) else markers
        if not _marker_applies(marker, environment, f"poetry.lock package {name}"):
            continue
        source = entry.get("source")
        if source:
            if source.get("type") != "legacy":
                raise LockfileError(
                    f"poetry.lock package {name} uses an unsupported {source.get('type')} "
                    "source; only registry packages are supported."
                )
            indexes.append(_index_url(source.get("url", ""), f"poetry.lock package {name}"))
        packages.append(
            _package(name, entry.get("version"), [item.get("hash") for item in entry.get("files", [])], "poetry.lock")
        )
    return packages, _ordered_unique(indexes)


# --- Pipenv ---------------------------------------------------------------

def pipfile_hash(pipfile: dict) -> str:
    """Pipenv (plette) ``Pipfile.get_hash`` over the parsed Pipfile."""
    data = {
        "_meta": {
            "sources": pipfile.get("source", [_DEFAULT_PIPFILE_SOURCE]),
            "requires": pipfile.get("requires", {}),
        },
        "default": pipfile.get("packages", {}),
        "develop": pipfile.get("dev-packages", {}),
    }
    for category, values in pipfile.items():
        if category not in _PIPFILE_SECTIONS and category not in ("default", "develop"):
            data[category] = values
    content = json.dumps(data, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def _load_pipenv(path: Path, environment):
    try:
        lock = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        raise LockfileError(f"Unable to parse Pipfile.lock: {exc}") from exc
    pipfile = _read_toml(_manifest(path, "Pipfile"))
    meta = lock.get("_meta", {})
    if meta.get("pipfile-spec") != 6:
        raise LockfileError("Pipfile.lock pipfile-spec is unsupported; relock with a current Pipenv.")
    if meta.get("hash", {}).get("sha256") != pipfile_hash(pipfile):
        raise _stale("Pipfile.lock", "pipenv lock")
    if environment is None:
        return [], []
    requires = meta.get("requires", {})
    if requires.get("python_version") and requires["python_version"] != environment["python_version"]:
        raise LockfileError(
            f"Pipfile.lock requires Python {requires['python_version']}, but the target "
            f"image provides {environment['python_full_version']}."
        )
    if requires.get("python_full_version") and requires["python_full_version"] != environment["python_full_version"]:
        raise LockfileError(
            f"Pipfile.lock requires Python {requires['python_full_version']}, but the target "
            f"image provides {environment['python_full_version']}."
        )
    sources = {source.get("name"): source.get("url") for source in meta.get("sources", [])}

    packages, indexes = [], []
    for name, entry in sorted(lock.get("default", {}).items()):
        if not isinstance(entry, dict):
            raise LockfileError(f"Pipfile.lock package {name} has an invalid entry.")
        unsupported = sorted({"editable", "git", "path", "file", "ref"} & set(entry))
        if unsupported:
            raise LockfileError(
                f"Pipfile.lock package {name} uses an unsupported {unsupported[0]} "
                "source; only registry packages are supported."
            )
        if not _marker_applies(entry.get("markers"), environment, f"Pipfile.lock package {name}"):
            continue
        version = str(entry.get("version", ""))
        if not version.startswith("=="):
            raise LockfileError(f"Pipfile.lock has no exact version for {name}.")
        index = entry.get("index")
        if index:
            if index not in sources:
                raise LockfileError(f"Pipfile.lock package {name} references unknown index {index!r}.")
            indexes.append(_index_url(sources[index], f"Pipfile.lock index {index}"))
        packages.append(_package(name, version[2:], entry.get("hashes", []), "Pipfile.lock"))
    return packages, _ordered_unique(indexes)


# --- PDM ------------------------------------------------------------------

def pdm_content_hash(pyproject: dict) -> str:
    """PDM ``PyProject.content_hash`` over the relevant pyproject data."""
    project = pyproject.get("project", {})
    settings = pyproject.get("tool", {}).get("pdm", {})
    groups: Dict[str, list] = {}
    for group, deps in pyproject.get("dependency-groups", {}).items():
        groups[canonical_name(group)] = list(deps)
    for group, deps in settings.get("dev-dependencies", {}).items():
        groups.setdefault(canonical_name(group), []).extend(deps)
    data = {
        "sources": settings.get("source", []),
        "dependencies": project.get("dependencies", []),
        "dev-dependencies": groups,
        "optional-dependencies": project.get("optional-dependencies", {}),
        "requires-python": project.get("requires-python", ""),
        "resolution": settings.get("resolution", {}),
    }
    return hashlib.sha256(json.dumps(data, sort_keys=True).encode("utf-8")).hexdigest()


def _load_pdm(path: Path, environment):
    lock = _read_toml(path)
    pyproject = _read_toml(_manifest(path, "pyproject.toml"))
    metadata = lock.get("metadata", {})
    if not str(metadata.get("lock_version", "")).startswith("4."):
        raise LockfileError("pdm.lock lock_version is unsupported; relock with PDM 2.11 or newer.")
    if "inherit_metadata" not in metadata.get("strategy", []):
        raise LockfileError(
            "pdm.lock was created without the inherit_metadata strategy, so target "
            "markers are not recorded; relock with `pdm lock --strategy inherit_metadata`."
        )
    algorithm, _, expected = str(metadata.get("content_hash", "")).partition(":")
    if algorithm != "sha256" or expected != pdm_content_hash(pyproject):
        raise _stale("pdm.lock", "pdm lock")
    targets = metadata.get("targets", [])
    if any(set(target) - {"requires_python"} for target in targets):
        raise LockfileError("pdm.lock platform-specific targets are unsupported; lock for requires-python only.")
    if environment is None:
        return [], []
    _require_python(pyproject.get("project", {}).get("requires-python"), environment, "pyproject.toml")
    if targets and not any(
        SpecifierSet(target.get("requires_python", "")).contains(
            environment["python_full_version"], prereleases=True
        )
        for target in targets
    ):
        raise LockfileError(
            f"pdm.lock has no target for Python {environment['python_full_version']}; "
            "add one with `pdm lock --python <specifier> --append`."
        )

    settings = pyproject.get("tool", {}).get("pdm", {})
    indexes = []
    for source in settings.get("source", []):
        if source.get("type", "index") != "index":
            raise LockfileError("PDM find_links sources are unsupported; use a package index.")
        indexes.append(_index_url(source.get("url", ""), f"PDM source {source.get('name', '')}"))

    packages = []
    for entry in lock.get("package", []):
        name = entry.get("name", "<unnamed>")
        unsupported = sorted({"path", "url", "git", "editable", "revision"} & set(entry))
        if unsupported:
            raise LockfileError(
                f"pdm.lock package {name} uses an unsupported {unsupported[0]} source; "
                "only registry packages are supported."
            )
        if "default" not in entry.get("groups", []):
            continue
        if not _marker_applies(entry.get("marker"), environment, f"pdm.lock package {name}"):
            continue
        packages.append(
            _package(name, entry.get("version"), [item.get("hash") for item in entry.get("files", [])], "pdm.lock")
        )
    return packages, _ordered_unique(indexes)


# --- uv -------------------------------------------------------------------

def _requirement_key(
    name: str, extras: Sequence[str], specifier: str, marker: Optional[str], environment, scenarios, source: str
) -> Tuple:
    try:
        specifiers = SpecifierSet(specifier or "")
    except InvalidSpecifier as exc:
        raise LockfileError(f"Invalid version specifier in {source}: {specifier!r}") from exc
    applies = () if environment is None else tuple(
        _marker_applies(marker, environment, source, extra) for extra in scenarios
    )
    return (canonical_name(name), tuple(sorted(canonical_name(extra) for extra in extras)), specifiers, applies)


def _pep508_key(text: str, environment, scenarios, source: str, extra: Optional[str] = None) -> Tuple:
    try:
        requirement = Requirement(text)
    except InvalidRequirement as exc:
        raise LockfileError(f"Invalid requirement in {source}: {text!r}") from exc
    if requirement.url:
        raise LockfileError(f"Direct URL requirement {requirement.name} in {source} is unsupported.")
    marker = str(requirement.marker) if requirement.marker else None
    if extra is not None:
        clause = f"extra == '{extra}'"
        marker = f"({marker}) and {clause}" if marker else clause
    return _requirement_key(
        requirement.name, sorted(requirement.extras), str(requirement.specifier), marker, environment, scenarios, source
    )


def _lock_requirement_key(entry: dict, environment, scenarios, source: str) -> Tuple:
    if not {"url", "git", "path", "directory", "editable"}.isdisjoint(entry):
        raise LockfileError(f"uv.lock requirement {entry.get('name')} uses an unsupported source.")
    return _requirement_key(
        entry.get("name", ""), entry.get("extras", []), entry.get("specifier", ""),
        entry.get("marker"), environment, scenarios, source,
    )


def _check_uv_fresh(lock: dict, root: dict, pyproject: dict, environment) -> None:
    project = pyproject.get("project", {})
    if project.get("requires-python") and lock.get("requires-python") != project["requires-python"]:
        raise _stale("uv.lock", "uv lock")
    optional = project.get("optional-dependencies", {})
    scenarios = ("", *sorted(canonical_name(extra) for extra in optional))
    expected = sorted(
        [_pep508_key(item, environment, scenarios, "pyproject.toml") for item in project.get("dependencies", [])]
        + [
            _pep508_key(item, environment, scenarios, "pyproject.toml", canonical_name(extra))
            for extra, items in optional.items()
            for item in items
        ],
        key=repr,
    )
    metadata = root.get("metadata", {})
    actual = sorted(
        (_lock_requirement_key(item, environment, scenarios, "uv.lock") for item in metadata.get("requires-dist", [])),
        key=repr,
    )
    expected_groups = {}
    groups = dict(pyproject.get("dependency-groups", {}))
    legacy = pyproject.get("tool", {}).get("uv", {}).get("dev-dependencies")
    if legacy:
        groups.setdefault("dev", []).extend(legacy)
    for group, items in groups.items():
        if any(not isinstance(item, str) for item in items):
            raise LockfileError("uv dependency-group includes are unsupported for lockfile staging.")
        expected_groups[canonical_name(group)] = sorted(
            (_pep508_key(item, environment, ("",), "pyproject.toml") for item in items), key=repr
        )
    actual_groups = {
        canonical_name(group): sorted(
            (_lock_requirement_key(item, environment, ("",), "uv.lock") for item in items), key=repr
        )
        for group, items in metadata.get("requires-dev", {}).items()
    }
    if expected != actual or expected_groups != actual_groups:
        raise _stale("uv.lock", "uv lock")


def _check_uv_complete(pyproject: dict, environment, selected, visited) -> None:
    """Fail when the locked root graph omits a manifest dependency for the target."""
    versions: Dict[str, List[str]] = {}
    for name, version in selected:
        versions.setdefault(name, []).append(version)
    for text in pyproject.get("project", {}).get("dependencies", []):
        try:
            requirement = Requirement(text)
        except InvalidRequirement as exc:
            raise LockfileError(f"Invalid requirement in pyproject.toml: {text!r}") from exc
        marker = str(requirement.marker) if requirement.marker else None
        if not _marker_applies(marker, environment, "pyproject.toml"):
            continue
        name = canonical_name(requirement.name)
        matches = [v for v in versions.get(name, []) if requirement.specifier.contains(v, prereleases=True)]
        extras = {canonical_name(extra) for extra in requirement.extras}
        covered = {
            canonical_name(extra)
            for state_name, state_version, state_extras in visited
            if state_name == name and state_version in matches
            for extra in state_extras
        }
        if not matches or not extras <= covered:
            raise LockfileError(
                f"uv.lock does not lock {requirement} for the target environment; run `uv lock`."
            )


def _check_uv_indexes(path: Path, lock: dict, settings: dict) -> None:
    if (path.parent / "uv.toml").exists() or {"index-url", "extra-index-url", "find-links"} & settings.keys():
        raise LockfileError("uv.lock staging requires project indexes to use [[tool.uv.index]] in pyproject.toml.")
    indexes = settings.get("index", [])
    allowed = {
        _index_url(index.get("url", ""), "tool.uv.index")
        for index in indexes
        if not index.get("explicit")
    }
    if not any(index.get("default") for index in indexes):
        allowed.add(None)  # uv's implicit PyPI index
    for entry in lock.get("package", []):
        registry = entry.get("source", {}).get("registry")
        if registry and _index_url(registry, "uv.lock package registry") not in allowed:
            raise _stale("uv.lock", "uv lock")


def _load_uv(path: Path, environment):
    lock = _read_toml(path)
    pyproject = _read_toml(_manifest(path, "pyproject.toml"))
    if lock.get("version") != 1:
        raise LockfileError("uv.lock version is unsupported; relock with a current uv.")
    if "manifest" in lock:
        raise LockfileError("uv workspaces, constraints and overrides are unsupported for lockfile staging.")
    uv_settings = pyproject.get("tool", {}).get("uv", {})
    unsupported = sorted(
        {"sources", "workspace", "override-dependencies", "constraint-dependencies"} & set(uv_settings)
    )
    if unsupported:
        raise LockfileError(f"uv tool.uv.{unsupported[0]} is unsupported for lockfile staging.")
    _check_uv_indexes(path, lock, uv_settings)

    by_name: Dict[str, List[dict]] = {}
    roots = []
    for entry in lock.get("package", []):
        source = entry.get("source", {})
        if source.get("virtual") == "." or source.get("editable") == ".":
            roots.append(entry)
        by_name.setdefault(canonical_name(entry.get("name", "")), []).append(entry)
    if len(roots) != 1:
        raise LockfileError("uv.lock must contain exactly one root project package.")
    root = roots[0]
    project_name = pyproject.get("project", {}).get("name")
    if not project_name or canonical_name(project_name) != canonical_name(root.get("name", "")):
        raise _stale("uv.lock", "uv lock")
    _check_uv_fresh(lock, root, pyproject, environment)
    if environment is None:
        return [], []
    _require_python(lock.get("requires-python"), environment, "uv.lock")

    selected: Dict[Tuple[str, str], dict] = {}
    pending = [(dependency, root.get("name")) for dependency in root.get("dependencies", [])]
    visited = set()
    while pending:
        dependency, parent = pending.pop()
        name = canonical_name(dependency.get("name", ""))
        if not _marker_applies(dependency.get("marker"), environment, f"uv.lock dependency of {parent}"):
            continue
        candidates = [
            entry
            for entry in by_name.get(name, [])
            if dependency.get("version") in (None, entry.get("version"))
            and dependency.get("source") in (None, entry.get("source"))
        ]
        if len(candidates) > 1:
            candidates = [
                entry
                for entry in candidates
                if any(
                    _marker_applies(marker, environment, f"uv.lock package {name}")
                    for marker in entry.get("resolution-markers", [None])
                )
            ]
        if len(candidates) != 1:
            raise LockfileError(f"uv.lock dependency {name} of {parent} does not identify one locked package.")
        entry = candidates[0]
        extras = tuple(sorted(dependency.get("extra", [])))
        state = (name, entry.get("version"), extras)
        if state in visited:
            continue
        visited.add(state)
        selected[(name, entry.get("version"))] = entry
        pending.extend((child, name) for child in entry.get("dependencies", []))
        optional = entry.get("optional-dependencies", {})
        for extra in extras:
            if extra not in optional:
                raise LockfileError(f"uv.lock package {name} has no locked extra {extra!r}.")
            pending.extend((child, name) for child in optional[extra])
    _check_uv_complete(pyproject, environment, selected, visited)

    packages, indexes = [], []
    for (name, _), entry in sorted(selected.items()):
        registry = entry.get("source", {}).get("registry")
        if not registry:
            kind = next(iter(entry.get("source", {})), "unknown")
            raise LockfileError(
                f"uv.lock package {name} uses an unsupported {kind} source; only "
                "registry packages are supported."
            )
        indexes.append(_index_url(registry, f"uv.lock package {name}"))
        artifacts = list(entry.get("wheels", []))
        if not artifacts:
            raise LockfileError(
                f"uv.lock package {name} {entry.get('version')} has no locked wheels; "
                "source distributions are not supported."
            )
        packages.append(_package(name, entry.get("version"), [item.get("hash") for item in artifacts], "uv.lock"))
    return packages, _ordered_unique(indexes)
