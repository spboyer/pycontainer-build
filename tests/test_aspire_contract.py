"""CLI and TOML contract relied on by spboyer/PyContainer.Aspire.Hosting.

The Aspire adapter shells out to ``pycontainer build`` with exactly these
arguments and a generated ``[build]`` file (see its PyContainerBuildPlan.cs and
PyContainerImageBuilder.cs). Renaming or removing any of them breaks Aspire
publishing, so change this test only together with the adapter.
"""

import sys

from pycontainer import cli


def test_aspire_adapter_build_and_push_contract(tmp_path, monkeypatch):
    context = tmp_path / "api"
    context.mkdir()
    output_dir = tmp_path / "obj" / "image"
    config_path = tmp_path / "pycontainer.toml"
    config_path.write_text(
        "# Generated by PyContainer.Aspire.Hosting. Do not edit.\n"
        "[build]\n"
        f"output-dir = \"{output_dir.as_posix()}\"\n"
        "workdir = \"/app\"\n"
        "entrypoint = [\"python\", \"-m\", \"uvicorn\"]\n"
        "\n"
        "[build.env]\n"
        "PYTHONUNBUFFERED = \"1\"\n"
        "PYTHONDONTWRITEBYTECODE = \"1\"\n"
    )
    calls = []

    class FakeImageBuilder:
        def __init__(self, config):
            calls.append(("config", config))

        def build(self):
            return "layout"

        def push(self, **kwargs):
            calls.append(("push", kwargs))

    monkeypatch.setattr(cli, "ImageBuilder", FakeImageBuilder)
    monkeypatch.setattr(sys, "argv", [
        "pycontainer", "build",
        "--config", str(config_path),
        "--context", str(context),
        "--tag", "api:latest",
        "--platform", "linux/arm64",
        "--no-progress",
        "--base-image", "python:3.12-slim",
        "--include-deps",
        "--requirements", ".pycontainer-aspire/api/requirements.txt",
        "--exclude", ".venv", "--exclude", "venv", "--exclude", "env",
        "--push",
        "--registry", "localhost:5443/samples/api:latest",
    ])

    cli.main()

    (_, config), (_, push) = calls
    assert config.output_dir == output_dir.as_posix()
    assert config.workdir == "/app"
    assert config.entrypoint == ["python", "-m", "uvicorn"]
    assert config.env == {"PYTHONUNBUFFERED": "1", "PYTHONDONTWRITEBYTECODE": "1"}
    assert config.context_dir == str(context)
    assert config.tag == "api:latest"
    assert config.platform == "linux/arm64"
    assert config.base_image == "python:3.12-slim"
    assert config.include_deps is True
    assert config.requirements_file == ".pycontainer-aspire/api/requirements.txt"
    assert config.exclude_paths == [".venv", "venv", "env"]
    assert push["registry_url"] == "localhost:5443/samples/api:latest"
    assert push["show_progress"] is False
